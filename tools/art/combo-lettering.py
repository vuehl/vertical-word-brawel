"""Build the combo caption from the same Swei Gothic Bold font as the game UI."""
import json
import math
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

ROOT = Path(__file__).resolve().parents[2]
font = TTFont(ROOT / "resources/public/fonts/swei/SweiGothicCJKsc-Bold.woff")
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()


class OutlinePen(BasePen):
    def __init__(self):
        super().__init__(glyphs)
        self.rings = []
        self.ring = []

    def _moveTo(self, p):
        self.ring = [p]

    def _lineTo(self, p):
        self.ring.append(p)

    def _qCurveToOne(self, control, end):
        start = self._getCurrentPoint()
        steps = max(4, math.ceil((math.dist(start, control) + math.dist(control, end)) / 30))
        for i in range(1, steps + 1):
            t = i / steps
            self.ring.append(tuple((1-t)**2*start[k]+2*(1-t)*t*control[k]+t*t*end[k] for k in (0, 1)))

    def _curveToOne(self, a, b, end):
        start = self._getCurrentPoint()
        for i in range(1, 21):
            t = i / 20
            self.ring.append(tuple((1-t)**3*start[k]+3*(1-t)**2*t*a[k]+3*(1-t)*t*t*b[k]+t**3*end[k] for k in (0, 1)))

    def _closePath(self):
        if self.ring:
            self.rings.append(self.ring)
            self.ring = []

    _endPath = _closePath


lettering = {}
for character in "连击":
    pen = OutlinePen()
    glyphs[cmap[ord(character)]].draw(pen)
    points = [p for ring in pen.rings for p in ring]
    x0, x1 = min(p[0] for p in points), max(p[0] for p in points)
    y0, y1 = min(p[1] for p in points), max(p[1] for p in points)
    height = 50
    scale = height / (y1-y0)
    width_scale = min(scale, 48 / (x1-x0))
    lettering[character] = []
    for ring in pen.rings:
        transformed = []
        for x, y in ring:
            py = (64-height)/2+(y1-y)*scale
            px = 32+(x-(x0+x1)/2)*width_scale
            transformed.extend((round(px, 2), round(py, 2)))
        lettering[character].append(transformed)

destination = ROOT / "source/src/effects/combo-lettering.js"
destination.write_text(
    "// Generated by tools/art/combo-lettering.py from the bundled Swei Gothic Bold (OFL).\n"
    "// Caption only: combo digits reuse the damage-number contours in battle-particles.js.\n"
    "export const comboLettering={\n" + ",\n".join(
        json.dumps(key, ensure_ascii=False) + ":" + json.dumps(value, separators=(",", ":"))
        for key, value in lettering.items()
    ) + "\n};\n", encoding="utf-8"
)
print(f"Generated {len(lettering)} UI caption glyphs: {destination.name}")
