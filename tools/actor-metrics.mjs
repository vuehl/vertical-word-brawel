import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

// Equivalent to the walk-frame bounds used by SpriteBatch.measure(). Compute
// once on the build machine; the phone only needs these three collision values.
export async function measureActor(input,meta,id){
  const frame=([50,51].includes(id)&&meta.anims?.idle)||meta.anims?.walk;
  if(!frame)throw Error('Missing actor walk frame: '+id);
  const {fw,fh,y}=frame;
  const rgba=await sharp(input).extract({left:0,top:y,width:fw,height:fh}).ensureAlpha().raw().toBuffer();
  let bottom=0,top=fh,left=fw,right=0;
  for(let y=0;y<fh;y++)for(let x=0;x<fw;x++)if(rgba[(y*fw+x)*4+3]>128){
    bottom=Math.max(bottom,y);top=Math.min(top,y);left=Math.min(left,x);right=Math.max(right,x);
  }
  if(bottom<=top)throw Error('Empty actor walk frame: '+id);
  return {foot:bottom+1-fh/2,top:top-fh/2,width:right-left+1};
}

export async function writeActorMetrics(source){
  const pub=path.join(source,'public'),metadata=JSON.parse(fs.readFileSync(path.join(pub,'data/sprites.json'))),metrics={};
  for(const id of [...Array.from({length:151},(_,i)=>i+1),201]){
    const key='assets/pmd/'+id+'.png',override=path.join(pub,'overrides',key);
    metrics[id]=await measureActor(fs.existsSync(override)?override:path.join(pub,key),metadata[id],id);
  }
  fs.writeFileSync(path.join(source,'src/actor-metrics.js'),'// Generated by tools/actor-metrics.mjs from original walk frames. Preserve gameplay bounds.\nexport const actorMetrics='+JSON.stringify(metrics)+';\n');
}
