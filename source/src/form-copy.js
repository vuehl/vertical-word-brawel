// Recipe and ultimate definitions are distinct catalogs. An identical original
// title can refer to different skills (for example 鲸's ultimate and fusion).
export const specialNames = Object.fromEntries(['ultimate', 'fusion', 'passive'].map(kind => [
  kind, new Map(Object.values(formCopy).flatMap(form => form[kind] ? [form[kind]] : [])),
]));

export function moveCopy(species, original, moveKey) {
  const form = formCopy[species];
  if (!form) return original;
  const slot = form.starterAttack;
  if (slot && moveKey === slot[0]) return form.moves[slot[1]];
  return form.moves[original] ?? original;
}


// Copied battle types (摹) take precedence while the effect is active.
export function displayedFormType(player) {
  const natural = player.types === player.data.types;
  return (natural && formCopy[player.speciesId]?.type) || player.types[0];
}
